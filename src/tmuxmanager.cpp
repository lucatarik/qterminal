#include "tmuxmanager.h"

#include "properties.h"

#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QJsonDocument>
#include <QProcess>
#include <QProcessEnvironment>
#include <QStandardPaths>
#include <QUuid>

static const char SOCKET_NAME[] = "qterminal";
static const char BOOT_SESSION[] = "qterminal-boot";
static const char RESURRECT_REPO[] = "https://github.com/tmux-plugins/tmux-resurrect.git";

TmuxManager *TmuxManager::instance()
{
    static TmuxManager *manager = new TmuxManager;
    return manager;
}

TmuxManager::TmuxManager()
    : m_tmux(QStandardPaths::findExecutable(QStringLiteral("tmux")))
{
    connect(&m_saveTimer, &QTimer::timeout, this, [this] { saveNow(); });
}

bool TmuxManager::isAvailable() const
{
    return !m_tmux.isEmpty();
}

bool TmuxManager::isActive() const
{
    return isAvailable() && !m_disabled && Properties::Instance()->tmuxEnabled;
}

QString TmuxManager::dataDir() const
{
    return QStandardPaths::writableLocation(QStandardPaths::AppDataLocation) + QStringLiteral("/tmux");
}

QString TmuxManager::configPath() const
{
    return dataDir() + QStringLiteral("/qterminal.conf");
}

QString TmuxManager::findPlugin(const QString &name) const
{
    const QString home = QDir::homePath();
    const QString xdgConfig = QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation);
    const QStringList candidates = {
        dataDir() + QStringLiteral("/plugins/") + name,
        home + QStringLiteral("/.tmux/plugins/") + name,
        xdgConfig + QStringLiteral("/tmux/plugins/") + name,
        QStringLiteral("/usr/share/") + name,
        QStringLiteral("/usr/share/tmux-plugins/") + name,
    };
    for (const QString &dir : candidates)
    {
        if (QFile::exists(dir + QStringLiteral("/resurrect.tmux")))
            return dir;
    }
    return QString();
}

bool TmuxManager::hasResurrect() const
{
    return !findPlugin(QStringLiteral("tmux-resurrect")).isEmpty();
}

void TmuxManager::prepare(QProcess &process) const
{
    QProcessEnvironment env = QProcessEnvironment::systemEnvironment();
    env.remove(QStringLiteral("TMUX"));
    env.remove(QStringLiteral("TMUX_PANE"));
    process.setProcessEnvironment(env);
    process.setProcessChannelMode(QProcess::SeparateChannels);
}

QStringList TmuxManager::serverArguments() const
{
    return {QStringLiteral("-L"), QLatin1String(SOCKET_NAME), QStringLiteral("-f"), configPath()};
}

QProcess *TmuxManager::start(const QStringList &args, QObject *parent) const
{
    if (!isAvailable())
        return nullptr;
    auto *process = new QProcess(parent);
    prepare(*process);
    process->start(m_tmux, serverArguments() + args);
    return process;
}

bool TmuxManager::run(const QStringList &args, QString *out, int timeoutMs) const
{
    if (!isAvailable())
        return false;
    QProcess process;
    prepare(process);
    process.start(m_tmux, serverArguments() + args);
    if (!process.waitForFinished(timeoutMs))
    {
        process.kill();
        process.waitForFinished(1000);
        return false;
    }
    if (out)
        *out = QString::fromUtf8(process.readAllStandardOutput());
    return process.exitStatus() == QProcess::NormalExit && process.exitCode() == 0;
}

bool TmuxManager::serverRunning() const
{
    return run({QStringLiteral("list-sessions")});
}

static QString quoted(const QString &path)
{
    // tmux single quotes cannot be escaped; such a path is not usable
    return path.contains(QLatin1Char('\'')) ? QString() : QLatin1Char('\'') + path + QLatin1Char('\'');
}

void TmuxManager::writeConfig() const
{
    QDir().mkpath(dataDir() + QStringLiteral("/resurrect"));

    QStringList conf;
    conf << QStringLiteral("# Generated by QTerminal at every start. Edit ~/.tmux.conf instead.");
    // defaults first, so that the user's own configuration can override them
    conf << QStringLiteral("set -g status off")           // the tabs are QTerminal's own
         << QStringLiteral("set -g set-titles on")        // the pane title becomes the tab title
         << QStringLiteral("set -g set-titles-string '#T'")
         << QStringLiteral("set -g history-limit 50000");
    if (Properties::Instance()->tmuxMouse)
    {
        conf << QStringLiteral("set -g mouse on");
    }
    else
    {
        // The terminal's own selection and scrollback keep working: tmux gets no
        // mouse and draws on the main screen instead of the alternate one.
        conf << QStringLiteral("set -g mouse off")
             << QStringLiteral("set -ga terminal-overrides ',*:smcup@:rmcup@'");
    }
    // QTermWidget has no OSC 52: a tmux selection reaches the clipboard through a command
    if (!QStandardPaths::findExecutable(QStringLiteral("wl-copy")).isEmpty() && qEnvironmentVariableIsSet("WAYLAND_DISPLAY"))
        conf << QStringLiteral("set -s copy-command 'wl-copy'");
    else if (!QStandardPaths::findExecutable(QStringLiteral("xclip")).isEmpty())
        conf << QStringLiteral("set -s copy-command 'xclip -in -selection clipboard'");
    else if (!QStandardPaths::findExecutable(QStringLiteral("xsel")).isEmpty())
        conf << QStringLiteral("set -s copy-command 'xsel --input --clipboard'");

    const QString xdgConfig = QStandardPaths::writableLocation(QStandardPaths::GenericConfigLocation);
    const QStringList userConfs{QDir::homePath() + QStringLiteral("/.tmux.conf"),
                                xdgConfig + QStringLiteral("/tmux/tmux.conf")};
    for (const QString &userConf : userConfs)
    {
        if (QFile::exists(userConf) && !quoted(userConf).isEmpty())
            conf << QStringLiteral("source-file -q ") + quoted(userConf);
    }

    // the setting wins over ~/.tmux.conf: with the mouse in tmux, the selection is tmux's
    if (!Properties::Instance()->tmuxMouse)
        conf << QStringLiteral("set -g mouse off");

    const QString plugin = findPlugin(QStringLiteral("tmux-resurrect"));
    const QString resurrectDir = quoted(dataDir() + QStringLiteral("/resurrect"));
    if (!plugin.isEmpty() && !resurrectDir.isEmpty() && !quoted(plugin).isEmpty())
    {
        conf << QStringLiteral("set -g @resurrect-dir ") + resurrectDir
             << QStringLiteral("set -g @resurrect-capture-pane-contents 'on'")
             << QStringLiteral("run-shell ") + quoted(plugin + QStringLiteral("/resurrect.tmux"));
    }

    QFile file(configPath());
    if (file.open(QIODevice::WriteOnly | QIODevice::Truncate))
        file.write(conf.join(QLatin1Char('\n')).toUtf8() + '\n');
}

void TmuxManager::installPlugins()
{
    if (m_installing || hasResurrect())
        return;
    const QString git = QStandardPaths::findExecutable(QStringLiteral("git"));
    if (git.isEmpty())
    {
        emit statusMessage(tr("tmux-resurrect not found and git is missing: sessions will not survive a restart of tmux."));
        return;
    }
    m_installing = true;
    auto *process = new QProcess(this);
    connect(process, &QProcess::finished, this, [this, process](int code, QProcess::ExitStatus status) {
        m_installing = false;
        process->deleteLater();
        if (status != QProcess::NormalExit || code != 0 || !hasResurrect())
        {
            emit statusMessage(tr("Could not download tmux-resurrect: sessions will not survive a restart of tmux."));
            return;
        }
        writeConfig();
        if (serverRunning())
            run({QStringLiteral("source-file"), configPath()});
        emit statusMessage(tr("tmux-resurrect installed."));
    });
    connect(process, &QProcess::errorOccurred, process, [this, process](QProcess::ProcessError) {
        if (process->state() == QProcess::NotRunning)
            m_installing = false;
    });
    process->start(git, {QStringLiteral("clone"), QStringLiteral("--depth"), QStringLiteral("1"),
                         QLatin1String(RESURRECT_REPO),
                         dataDir() + QStringLiteral("/plugins/tmux-resurrect")});
}

void TmuxManager::setupSaveTimer()
{
    const int minutes = qMax(1, Properties::Instance()->tmuxSaveIntervalMinutes);
    m_saveTimer.start(minutes * 60 * 1000);
}

void TmuxManager::start()
{
    if (!isActive())
        return;
    writeConfig();
    if (hasResurrect() && !serverRunning())
        restoreSaved();
    else if (!hasResurrect())
        installPlugins();
    setupSaveTimer();
}

QString TmuxManager::newSessionName() const
{
    return QStringLiteral("qt-") + QUuid::createUuid().toString(QUuid::Id128).left(8);
}

QStringList TmuxManager::clientCommand(const QString &session, const QString &directory, const QStringList &userShell) const
{
    // "env -u TMUX": tmux refuses to nest when the program itself runs inside tmux
    QStringList cmd{QStandardPaths::findExecutable(QStringLiteral("env")),
                    QStringLiteral("-u"), QStringLiteral("TMUX"), QStringLiteral("-u"), QStringLiteral("TMUX_PANE"),
                    m_tmux, QStringLiteral("-L"), QLatin1String(SOCKET_NAME), QStringLiteral("-f"), configPath(),
                    QStringLiteral("new-session"), QStringLiteral("-A"), QStringLiteral("-s"), session};
    if (!directory.isEmpty())
        cmd << QStringLiteral("-c") << directory;
    cmd << userShell;
    return cmd;
}

QStringList TmuxManager::detachedSessions() const
{
    QString out;
    if (!run({QStringLiteral("list-sessions"), QStringLiteral("-F"),
              QStringLiteral("#{session_created}\t#{session_attached}\t#{session_name}")}, &out))
    {
        return {};
    }
    QList<QPair<qint64, QString>> found;
    const QStringList lines = out.split(QLatin1Char('\n'), Qt::SkipEmptyParts);
    for (const QString &line : lines)
    {
        const QStringList parts = line.split(QLatin1Char('\t'));
        if (parts.size() < 3 || parts.at(1).toInt() != 0 || parts.at(2) == QLatin1String(BOOT_SESSION))
            continue;
        found.append({parts.at(0).toLongLong(), parts.at(2)});
    }
    std::sort(found.begin(), found.end());
    QStringList names;
    for (const auto &item : std::as_const(found))
        names << item.second;
    return names;
}

QString TmuxManager::paneCurrentPath(const QString &session) const
{
    QString out;
    if (!run({QStringLiteral("display-message"), QStringLiteral("-p"), QStringLiteral("-t"),
              QLatin1Char('=') + session + QLatin1Char(':'), QStringLiteral("#{pane_current_path}")}, &out, 1000))
    {
        return QString();
    }
    return out.trimmed();
}

bool TmuxManager::sessionBusy(const QString &session) const
{
    QString out;
    if (!run({QStringLiteral("list-panes"), QStringLiteral("-s"), QStringLiteral("-t"),
              QLatin1Char('=') + session + QLatin1Char(':'), QStringLiteral("-F"),
              QStringLiteral("#{pane_current_command}")}, &out, 1000))
    {
        return false;
    }
    static const QStringList shells{QStringLiteral("bash"), QStringLiteral("zsh"), QStringLiteral("fish"),
                                    QStringLiteral("sh"), QStringLiteral("dash"), QStringLiteral("ksh"),
                                    QStringLiteral("tcsh"), QStringLiteral("csh"), QStringLiteral("nu"),
                                    QStringLiteral("elvish"), QStringLiteral("xonsh")};
    const QString userShell = QFileInfo(qEnvironmentVariable("SHELL")).fileName();
    const QStringList commands = out.split(QLatin1Char('\n'), Qt::SkipEmptyParts);
    for (QString command : commands)
    {
        command = command.trimmed();
        if (command.startsWith(QLatin1Char('-'))) // login shell
            command.remove(0, 1);
        if (!shells.contains(command) && command != userShell)
            return true;
    }
    return false;
}

void TmuxManager::killSession(const QString &session) const
{
    if (!isAvailable() || session.isEmpty())
        return;
    QProcess::startDetached(m_tmux, {QStringLiteral("-L"), QLatin1String(SOCKET_NAME),
                                     QStringLiteral("kill-session"), QStringLiteral("-t"),
                                     QLatin1Char('=') + session});
}

void TmuxManager::scrollProgram(const QString &session, int lines, int column, int row, bool page) const
{
    if (!isAvailable() || session.isEmpty() || lines == 0)
        return;
    const QString target = QLatin1Char('=') + session + QLatin1Char(':');
    const QString count = QString::number(qAbs(lines));

    // Only a full screen program (alternate screen) or one that tracks the mouse owns
    // its scrolling; the history of anything else is shown by TmuxScrollBar.
    QString flags;
    if (run({QStringLiteral("display-message"), QStringLiteral("-p"), QStringLiteral("-t"), target,
             QStringLiteral("#{pane_in_mode} #{alternate_on} #{mouse_any_flag} #{mouse_sgr_flag}")}, &flags, 1000))
    {
        const QStringList f = flags.trimmed().split(QLatin1Char(' '));
        if (f.size() == 4 && f.at(0) == QLatin1String("0"))
        {
            if (f.at(2) == QLatin1String("1") && f.at(3) == QLatin1String("1"))
            {
                // wheel as the program asked for it: SGR button 64 (up) or 65 (down), 1-based cell
                const QByteArray seq = "\x1b[<" + QByteArray::number(lines > 0 ? 64 : 65) + ';'
                                       + QByteArray::number(column + 1) + ';' + QByteArray::number(row + 1) + 'M';
                QStringList args{QStringLiteral("send-keys"), QStringLiteral("-t"), target, QStringLiteral("-H")};
                const QByteArray hex = seq.toHex(' ');
                for (int i = 0; i < qMax(1, qAbs(lines) / 3); ++i)
                    args << QString::fromLatin1(hex).split(QLatin1Char(' '));
                run(args, nullptr, 1000);
                return;
            }
            if (f.at(1) == QLatin1String("1"))
            {
                // no mouse tracking: the cursor keys, like the alternate scroll mode of a terminal
                // a page asked for goes as one PageUp/PageDown, which the program knows how to size
                run({QStringLiteral("send-keys"), QStringLiteral("-t"), target, QStringLiteral("-N"), page ? QStringLiteral("1") : count,
                     page ? (lines > 0 ? QStringLiteral("PageUp") : QStringLiteral("PageDown"))
                          : (lines > 0 ? QStringLiteral("Up") : QStringLiteral("Down"))}, nullptr, 1000);
                return;
            }
        }
    }
}

void TmuxManager::clearPane(const QString &session) const
{
    const QString target = QLatin1Char('=') + session + QLatin1Char(':');
    run({QStringLiteral("clear-history"), QStringLiteral("-t"), target}, nullptr, 1000);
    run({QStringLiteral("send-keys"), QStringLiteral("-t"), target, QStringLiteral("C-l")}, nullptr, 1000);
}

void TmuxManager::saveNow(bool wait)
{
    const QString plugin = findPlugin(QStringLiteral("tmux-resurrect"));
    if (!isActive() || plugin.isEmpty() || !serverRunning())
        return;
    emit layoutRequested();
    const QString script = plugin + QStringLiteral("/scripts/save.sh");
    if (wait)
    {
        run({QStringLiteral("run-shell"), QStringLiteral("'") + script + QStringLiteral("' quiet")}, nullptr, 15000);
        return;
    }
    // "-b": tmux runs the script in the background and returns at once
    QProcess::startDetached(m_tmux, {QStringLiteral("-L"), QLatin1String(SOCKET_NAME),
                                     QStringLiteral("run-shell"), QStringLiteral("-b"),
                                     QStringLiteral("'") + script + QStringLiteral("' quiet")});
}

bool TmuxManager::restoreSaved()
{
    const QString plugin = findPlugin(QStringLiteral("tmux-resurrect"));
    if (!isActive() || plugin.isEmpty())
        return false;
    writeConfig();
    const bool wasRunning = serverRunning();
    if (!wasRunning
        && !run({QStringLiteral("new-session"), QStringLiteral("-d"), QStringLiteral("-s"), QLatin1String(BOOT_SESSION)}))
    {
        return false;
    }
    const bool ok = run({QStringLiteral("run-shell"),
                         QStringLiteral("'") + plugin + QStringLiteral("/scripts/restore.sh'")}, nullptr, 60000);
    if (!wasRunning)
    {
        // the bootstrap session only keeps the new server alive while restoring
        if (!detachedSessions().isEmpty())
            run({QStringLiteral("kill-session"), QStringLiteral("-t"), QLatin1Char('=') + QLatin1String(BOOT_SESSION)});
    }
    return ok;
}

QJsonArray TmuxManager::loadLayout() const
{
    QFile file(dataDir() + QStringLiteral("/layout.json"));
    if (!file.open(QIODevice::ReadOnly))
        return QJsonArray();
    return QJsonDocument::fromJson(file.readAll()).array();
}

void TmuxManager::saveLayout(const QJsonArray &tabs) const
{
    QDir().mkpath(dataDir());
    QFile file(dataDir() + QStringLiteral("/layout.json"));
    if (file.open(QIODevice::WriteOnly | QIODevice::Truncate))
        file.write(QJsonDocument(tabs).toJson(QJsonDocument::Compact));
}
